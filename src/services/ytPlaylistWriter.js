import {
  getAllPlaylistsForWriter,
  getPlaylistItemsForWriter,
  createPlaylist,
  addVideoToPlaylist,
  updatePlaylistTitle,
} from "./youtube";
import { createPlaylistKey } from "../utils/helper.js";

const YTWL_PREFIX = "YTWL:v1:";

function createYTWLId(playlist) {
  const ytwlId = `${YTWL_PREFIX}${createPlaylistKey(playlist.meta.values)}`;

  return ytwlId;
}

function createPlaylistDescription(ytwlId) {
  const description = ["Generated by YT Watch Later", "", ytwlId].join("\n");

  return description;
}

async function findGeneratedPlaylist(accessToken, ytwlId) {
  const cache = await getAllPlaylistsForWriter(accessToken);

  const found = cache.generatedByYtwlId.get(ytwlId);

  if (found) {
    return found;
  }

  return null;
}

async function getExistingVideoIds(accessToken, playlistId) {
  const videoIds = new Set();

  let pageToken = "";
  let page = 1;

  while (true) {
    const response = await getPlaylistItemsForWriter(
      accessToken,
      playlistId,
      pageToken
    );

    const items = response.items || [];

    for (const videoId of items) {
      videoIds.add(videoId);
    }

    if (!response.nextPageToken) {
      break;
    }

    pageToken = response.nextPageToken;
    page++;
  }

  return videoIds;
}

async function waitForNewPlaylist(accessToken, playlistId) {
  const maxAttempts = 5;

  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    try {
      const response = await getPlaylistItemsForWriter(accessToken, playlistId);

      return new Set(response.items || []);
    } catch (error) {
      console.error("Error in waitforplaylist", error);
      const isPropagationError =
        error?.status === 404 && error?.reason === "playlistNotFound";

      if (!isPropagationError || attempt === maxAttempts) {
        throw error;
      }

      const delay = 1000 * 2 ** (attempt - 1);

      await new Promise((resolve) => setTimeout(resolve, delay));
    }
  }

  throw new Error("New YouTube playlist did not become available");
}

export async function syncGeneratedPlaylist(
  accessToken,
  generatedPlaylist,
  onProgress
) {
  if (!accessToken) {
    console.error("[YTWL] ERROR: accessToken is missing!");
    throw new Error("YouTube access token is missing");
  }

  if (!generatedPlaylist) {
    console.error("[YTWL] ERROR: generatedPlaylist is missing!");
    throw new Error("generatedPlaylist is missing");
  }

  const ytwlId = createYTWLId(generatedPlaylist);

  // Tell UI we're starting this playlist.
  onProgress?.({
    type: "playlist-start",
    playlistName: generatedPlaylist.name,
    status: "starting",
  });

  // Find existing playlist.
  let youtubePlaylist = await findGeneratedPlaylist(accessToken, ytwlId);

  let created = false;
  let existingVideoIds;

  // No existing playlist → create it.
  if (!youtubePlaylist) {
    onProgress?.({
      type: "playlist-creating",
      playlistName: generatedPlaylist.name,
      status: "creating",
    });

    const description = createPlaylistDescription(ytwlId);

    youtubePlaylist = await createPlaylist(
      accessToken,
      generatedPlaylist.name,
      description,
      "private"
    );

    created = true;
  } else {
    if (youtubePlaylist.title !== generatedPlaylist.name) {
      youtubePlaylist = await updatePlaylistTitle(
        accessToken,
        youtubePlaylist,
        generatedPlaylist.name
      );
    }
  }

  const playlistId = youtubePlaylist.id;

  if (!playlistId) {
    console.error(
      "[YTWL] ERROR: YouTube playlist was returned without an ID!",
      youtubePlaylist
    );

    throw new Error("YouTube playlist ID is missing");
  }

  // Get existing videos.
  if (created) {
    existingVideoIds = await waitForNewPlaylist(accessToken, playlistId);
  } else {
    existingVideoIds = await getExistingVideoIds(accessToken, playlistId);
  }

  const desiredVideoIds = new Set(generatedPlaylist.videoIds || []);

  const alreadyPresent = [];
  const videosToInsert = [];

  for (const videoId of desiredVideoIds) {
    if (existingVideoIds.has(videoId)) {
      alreadyPresent.push(videoId);
    } else {
      videosToInsert.push(videoId);
    }
  }

  // Tell UI how many songs actually need to be added.
  onProgress?.({
    type: "videos-start",
    playlistName: generatedPlaylist.name,
    totalVideos: desiredVideoIds.size,
    alreadyPresent: alreadyPresent.length,
    videosToAdd: videosToInsert.length,
    completedVideos: 0,
  });

  // Insert missing videos.
  const added = [];
  const failed = [];

  for (let i = 0; i < videosToInsert.length; i++) {
    const videoId = videosToInsert[i];

    try {
      await addVideoToPlaylist(accessToken, playlistId, videoId);

      added.push(videoId);

      onProgress?.({
        type: "video-progress",
        playlistName: generatedPlaylist.name,
        totalVideos: desiredVideoIds.size,
        alreadyPresent: alreadyPresent.length,
        videosToAdd: videosToInsert.length,
        completedVideos: i + 1,
        addedVideos: added.length,
        failedVideos: failed.length,
      });
    } catch (error) {
      console.error(`[YTWL] FAILED to add video: ${videoId}`, error);

      failed.push({
        videoId,
        error: error?.message || String(error),
      });

      onProgress?.({
        type: "video-error",
        playlistName: generatedPlaylist.name,
        videoId,
        error: error?.message || String(error),
        source: error?.source || "youtube",
        status: error?.status,
        reason: error?.reason,
      });
      // Still report progress because this video has been processed.
      onProgress?.({
        type: "video-progress",
        playlistName: generatedPlaylist.name,
        totalVideos: desiredVideoIds.size,
        alreadyPresent: alreadyPresent.length,
        videosToAdd: videosToInsert.length,
        completedVideos: i + 1,
        addedVideos: added.length,
        failedVideos: failed.length,
      });
    }
  }

  let status = "completed";

  if (failed.length > 0) {
    if (added.length > 0) {
      status = "partial";
    } else {
      status = "failed";
    }
  }

  const result = {
    name: generatedPlaylist.name,
    ytwlId,
    youtubePlaylistId: playlistId,
    created,
    status,
    totalVideos: desiredVideoIds.size,
    alreadyPresent,
    added,
    failed,
  };

  onProgress?.({
    type: "playlist-complete",
    playlistName: generatedPlaylist.name,
    status,
    totalVideos: desiredVideoIds.size,
    addedVideos: added.length,
    failedVideos: failed.length,
  });

  return result;
}
